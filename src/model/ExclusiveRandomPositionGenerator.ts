import { ExclusiveRng, IExclusiveRng } from "./ExclusiveRandomNumberGenerator";
import { Position } from "./Position";

/**
 * Checks if given position is between the given corners, inclusive.
 * @param minCorner Minimum corner of the range.
 * @param maxCorner Maximum corner of the range.
 * @param target Position to check if it is in bounds.
 * @returns True if target is between corners, inclusive, false otheriwse.
 */
function inBounds(
  minCorner: Position,
  maxCorner: Position,
  target: Position
): boolean {
  return (
    minCorner.getX() <= target.getX() &&
    minCorner.getY() <= target.getY() &&
    minCorner.getZ() <= target.getZ() &&
    target.getX() <= maxCorner.getX() &&
    target.getY() <= maxCorner.getY() &&
    target.getZ() <= maxCorner.getZ()
  );
}

class ExclusiveRandomPositionGenerator {
  private minCorner: Position;
  private maxCorner: Position;
  private rng: IExclusiveRng;

  /**
   * @brief Creates a new ExclusiveRandomPosition generator that generates
   *        random exclusive positions in the given range.
   * @param minCorner Box vertex that defines the lowest coordinate to be
   *        generated.
   * @param maxCorner Box vertex that defines the biggest coordinate to be
   *        generated.
   * @param rng Exclusive random number generator to be used by the algorithm.
   *        Must have a valid range of [0, n[ where n is the amount of
   *        positions in box enclosed by corners
   */
  constructor(
    minCorner: Position,
    maxCorner: Position,
    rng: IExclusiveRng = new ExclusiveRng(
      0,
      this.positionToNumber(maxCorner),
      []
    )
  ) {
    this.minCorner = minCorner;
    this.maxCorner = maxCorner;
    this.rng = rng;
  }

  /**
   * @brief Replaces an old occupated position with a new occupated position.
   * @param oldPos Old occupated position to replace.
   * @param newPos New occupated position to use as replacement.
   * @throws InvalidRangeError if the new occupated position has already been
   *         occupated (and it is not the old position to be replaced) or is
   *         outside the valid range, or if the old position is not occupated.
   */
  public updateOccupated(oldPos: Position, newPos: Position): void {
    this.rng.updateExcluded(
      this.positionToNumber(oldPos),
      this.positionToNumber(newPos)
    );
  }

  /**
   * @brief Adds a new occupated position.
   * @param newPos New position to be occupated.
   * @throws InvalidRangeError if the new occupated position is already
   *         occupated or if it is outside the valid range.
   */
  public addOcuppated(newPos: Position): void {
    this.rng.addExcluded(this.positionToNumber(newPos));
  }

  /**
   * @brief Generates a random position in the valid range, excluding occupated
   *        positions, following the distribution of the given ExclusiveRng.
   * @returns A random position that is not occupated in the valid range.
   * @throws InvalidRangeError if no position has probability of appearing.
   */
  public generate(): Position {
    const ret = this.numberToPosition(this.rng.generateRandomNumber());
    console.log(ret);
    return ret;
  }

  /**
   * @brief Produces an integer uniquely identifying the given position.
   * @param pos The position to convert. It must be in the range defined by the
   *        given sideAbsLimit.
   * @returns An integer that uniquely identifies the position. Must be between
   *          the number generated by the corner in the I octant and the number
   *          generated by the corner in the VII octant, inclusive.
   */
  private positionToNumber(pos: Position): number {
    const width = this.maxCorner.getX() - this.minCorner.getX() + 1;
    const depth = this.maxCorner.getY() - this.minCorner.getY() + 1;
    const xOffset = pos.getX() - this.minCorner.getX();
    const yOffset = pos.getY() - this.minCorner.getY();
    const zOffset = pos.getZ() - this.minCorner.getZ();
    return xOffset + yOffset * width + zOffset * width * depth;
  }

  private numberToPosition(num: number): Position {
    const width = this.maxCorner.getX() - this.minCorner.getX() + 1;
    const depth = this.maxCorner.getY() - this.minCorner.getY() + 1;
    const xOffset = num % width;
    const yOffset = ((num - xOffset) % (width * depth)) / width;
    const zOffset = (num - xOffset - yOffset * width) / (width * depth);
    return new Position(
      this.minCorner.getX() + xOffset,
      this.minCorner.getY() + yOffset,
      this.minCorner.getZ() + zOffset
    );
  }
}

export { ExclusiveRandomPositionGenerator };
